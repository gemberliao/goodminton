import tailwindcss from '@tailwindcss/vite';
import react from '@vitejs/plugin-react';
import path from 'path';
import {defineConfig} from 'vite';

export default defineConfig(() => {
  const [githubOwner, githubRepository] = (process.env.GITHUB_REPOSITORY || '').split('/');
  const isGitHubUserSite = githubRepository?.toLowerCase() === `${githubOwner?.toLowerCase()}.github.io`;
  const base = process.env.GITHUB_ACTIONS === 'true' && githubRepository
    ? (isGitHubUserSite ? '/' : `/${githubRepository}/`)
    : '/';

  return {
    base,
    plugins: [react(), tailwindcss()],
    resolve: {
      alias: {
        '@': path.resolve(__dirname, '.'),
      },
    },
    build: {
      rollupOptions: {
        output: {
          manualChunks(id) {
            if (!id.includes('node_modules')) return;
            if (id.includes('@fullcalendar')) return 'calendar-vendor';
            if (id.includes('@supabase') || id.includes('phoenix')) return 'data-service-vendor';
            if (
              id.includes('/react/') ||
              id.includes('/react-dom/') ||
              id.includes('react-router') ||
              id.includes('/scheduler/')
            ) {
              return 'react-vendor';
            }
          },
        },
      },
    },
    server: {
      // HMR is disabled in AI Studio via DISABLE_HMR env var.
      // Do not modifyâfile watching is disabled to prevent flickering during agent edits.
      hmr: process.env.DISABLE_HMR !== 'true',
      // Disable file watching when DISABLE_HMR is true to save CPU during agent edits.
      watch: process.env.DISABLE_HMR === 'true' ? null : {},
    },
  };
});
